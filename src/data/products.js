// Format price with Vietnamese dong
export function formatPrice(price, currency = '₫') {
  return `${currency} ${price.toLocaleString('en-US')}`;
}

// Get products by category
export function getProductsByCategory(category) {
  if (!category || category === 'all') return products;
  return products.filter(p => p.category === category);
}

// Get product by ID
export function getProductById(id) {
  return products.find(p => p.id === id);
}

// Get related products (same collection, excluding current)
export function getRelatedProducts(productId, limit = 6) {
  const product = getProductById(productId);
  if (!product) return products.slice(0, limit);

  const related = products.filter(p =>
    p.id !== productId && p.collection === product.collection
  );

  // Fill remaining spots with other products
  if (related.length < limit) {
    const others = products.filter(p =>
      p.id !== productId && p.collection !== product.collection
    );
    return [...related, ...others].slice(0, limit);
  }

  return related.slice(0, limit);
}
